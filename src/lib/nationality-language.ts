// Derive a student's mother tongue (language NAME, e.g. "Spanish") from their
// nationality (country name). Source of truth = the long-established langmap
// (THE estate language map, hub .knowledge/kb/markets/lang-map.json, published at
// https://hub.ulearnschool.com/hubapp/lang-map.json and synced into `data/lang-map.json` at start-up + daily —
// that local copy is only the fallback for when the hub can't be reached; never edit it by hand),
// which is stored inverted as { Language: [countries…] }. We build a
// country→language index from it once.
//
// A handful of nationalities arrive from HubSpot/CLDR under names the langmap
// doesn't carry ("Türkiye" vs "Turkey", "Czechia", the split Congos, etc.) — the
// OVERRIDES table maps those to a language (using the map's own language names).
// Fill-only by design: callers must never overwrite an existing language.
import fs from 'fs';
import path from 'path';

let _index: Record<string, string> | null = null;

// Sync the local copy from THE estate map (same pattern as ../scripts/territories.ts). On success the index is
// rebuilt from the fresh copy; on failure the last good copy keeps serving.
const LANG_MAP_URL = process.env.LANG_MAP_URL || 'https://hub.ulearnschool.com/hubapp/lang-map.json';
const LANG_MAP_CACHE = path.join(__dirname, '../../data/lang-map.json');
export async function refreshLangMap(): Promise<boolean> {
  try {
    const r = await fetch(LANG_MAP_URL, { signal: AbortSignal.timeout(15000) });
    if (!r.ok) throw new Error('HTTP ' + r.status);
    const m = await r.json();
    const lists = Object.values(m || {}).filter(Array.isArray) as unknown[][];
    if (lists.length < 20 || lists.reduce((n, l) => n + l.length, 0) < 150) throw new Error('unexpected content');
    fs.writeFileSync(LANG_MAP_CACHE, JSON.stringify(m, null, 2) + '\n');
    _index = null;
    writeBrowserMap();
    return true;
  } catch (e: any) {
    console.warn('[lang-map] refresh failed, keeping last good copy:', e?.message || e);
    return false;
  }
}
refreshLangMap();
setInterval(refreshLangMap, 24 * 3600e3).unref();

function loadIndex(): Record<string, string> {
  if (_index) return _index;
  const candidates = [
    path.join(process.cwd(), 'data/lang-map.json'),
    path.join(__dirname, '../../data/lang-map.json'),
  ];
  const file = candidates.find(p => { try { return fs.existsSync(p); } catch { return false; } });
  const idx: Record<string, string> = {};
  if (file) {
    try {
      const map = JSON.parse(fs.readFileSync(file, 'utf8'));
      for (const [lang, countries] of Object.entries(map)) {
        if (!Array.isArray(countries)) continue;   // skips the `metadata` entry
        for (const c of countries) idx[String(c).trim().toLowerCase()] = String(lang);
      }
    } catch { /* leave idx empty — derivation just returns null */ }
  }
  _index = idx;
  return idx;
}

// SIS/HubSpot nationality names the langmap doesn't carry → language name.
// Keys are lower-cased. Values use the langmap's own language vocabulary.
const OVERRIDES: Record<string, string> = {
  'türkiye': 'Turkish',
  'czechia': 'Czech',
  'congo - brazzaville': 'French',
  'congo - kinshasa': 'French',
  'palestinian territories': 'Arabic',
  'palestine': 'Arabic',
  'hong kong sar china': 'Chinese',
  'côte d’ivoire': 'French',
  "côte d'ivoire": 'French',
  'bosnia & herzegovina': 'Bosnian',
  'andorra': 'Spanish',           // langmap has no Catalan
  'antigua & barbuda': 'English',
  'western sahara': 'Arabic',
  'north macedonia': 'Macedonian',
  'haiti': 'French',              // langmap has no Haitian Creole
  'japanese': 'Japanese',          // demonym entered as a nationality
};

/** Mother tongue (language name) for a nationality, or null if unknown. */
export function languageForNationality(nationality: string | null | undefined): string | null {
  if (!nationality) return null;
  const key = String(nationality).trim().toLowerCase();
  if (!key) return null;
  return OVERRIDES[key] || loadIndex()[key] || null;
}

// Browser copy of the SAME country→language index (+ OVERRIDES) for the student app's challenge i18n
// (public/challenge-i18n.js reads window.ULEARN_COUNTRY_LANGUAGE), so the page never carries its own typed list.
// Rewritten at start-up and after every successful refresh.
function writeBrowserMap(): void {
    try {
        const idx = { ...loadIndex(), ...OVERRIDES };
        const out = path.join(__dirname, '../../public/lang-map.js');
        fs.writeFileSync(out, '// GENERATED by lib/nationality-language — canonical: hub .knowledge/kb/markets/lang-map.json. Do not edit.\nwindow.ULEARN_COUNTRY_LANGUAGE = ' + JSON.stringify(idx) + ';\n');
    }
    catch (e: any) {
        console.warn('[lang-map] browser copy not written:', e?.message || e);
    }
}
writeBrowserMap();
